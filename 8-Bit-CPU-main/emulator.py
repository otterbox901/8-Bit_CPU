#
#  Verification helpers
#

EXPECTED_RESULTS = {
    0x83: (0xAA, "STORE"),
    0x84: (0xFF, "ADD"),
    0x85: (0xAA, "SUB"),
    0x86: (0x55, "MOV"),
    0x87: (0x55, "JZ"),
    0x88: (0x55, "JC"),
}


def verify(cpu):
    """Check expected data RAM values; return (pass_count, fail_count)."""
    passed = failed = 0
    print("\n=== Result Verification ===")
    for addr, (expected, test_name) in sorted(EXPECTED_RESULTS.items()):
        actual = cpu.data_ram[addr]
        ok = actual == expected
        status = "PASS" if ok else "FAIL"
        print(f"  RAM[0x{addr:02X}] = 0x{actual:02X}  "
              f"(expected 0x{expected:02X})  [{test_name}] {status}")
        if ok:
            passed += 1
        else:
            failed += 1
    return passed, failed


def dump_ram(cpu, start=0x80, end=0x90):
    print(f"\n=== Data RAM dump 0x{start:02X}–0x{end-1:02X} ===")
    for addr in range(start, end, 16):
        hexbytes = " ".join(f"{cpu.data_ram[a]:02X}" for a in range(addr, min(addr+16, end)))
        print(f"  0x{addr:02X}: {hexbytes}")


#
#  Main
#

def find_microcode_file():
    """Search for microcode_table.csv or micro_table.csv in common locations."""
    candidates = [
        "microcode_table.csv",
        "micro_table.csv",
        "ROM/microcode_table.csv",
        "ROM/micro_table.csv",
    ]
    for p in candidates:
        if os.path.isfile(p):
            return p
    return None


def main():
    verbose = "--trace-micro" in sys.argv
    quiet   = "-q" in sys.argv
    args = [a for a in sys.argv[1:] if not a.startswith("-")]

    #  Load microcode table
    mc_path = find_microcode_file()
    if mc_path is None:
        print("Error: cannot find microcode_table.csv (or micro_table.csv).")
        print("Run microcode_rom_gen.py first to generate it.")
        sys.exit(1)

    cpu = CPU()
    print(f"Loading microcode table: {mc_path}")
    cpu.load_microcode(mc_path)
    print(f"  → {len(cpu.ctrl_rom)} control-word entries loaded.")

    # Assemble program
    asm = Assembler()
    if args:
        asm_path = args[0]
        print(f"Assembling: {asm_path}")
        with open(asm_path) as f:
            source = f.read()
    else:
        print("Using embedded test program (pass a .asm file to override).")
        source = DEFAULT_TEST_PROGRAM

    prog, data_ram = asm.assemble(source)
    if asm.errors:
        print("Assembly errors:")
        for e in asm.errors:
            print(f"  {e}")
        sys.exit(1)

    # Load program and data into CPU
    cpu.prog_rom[:len(prog)] = prog
    cpu.data_ram = data_ram

    print(f"  → {len(prog)} bytes assembled, "
          f"{sum(1 for v in data_ram if v)} data RAM cells initialized.")

    # Print assembled binary
    if not quiet:
        print(f"\n=== Program ROM ({len(prog)} bytes) ===")
        for i in range(0, len(prog), 16):
            chunk = prog[i:i+16]
            hexbytes = " ".join(f"{b:02X}" for b in chunk)
            print(f"  0x{i:02X}: {hexbytes}")

    #  Execute
    print(f"\n{'='*60}")
    print(" Execution trace")
    print(f"{'='*60}")
    halted = cpu.run(verbose=not quiet, trace_micro=verbose)

    print(f"\n{'='*60}")
    if halted:
        print(f" Execution complete — HLT reached")
    else:
        print(f" Execution STOPPED (no HLT, cycle limit)")
    print(f"   Micro-steps executed : {cpu.cycles}")
    print(f"   Instructions retired: {cpu.instr_count}")
    print(f"   Registers: R0=0x{cpu.regs[0]:02X}  R1=0x{cpu.regs[1]:02X}  "
          f"R2=0x{cpu.regs[2]:02X}  R3=0x{cpu.regs[3]:02X}")
    print(f"   Flags: Z={cpu.flag_z}  C={cpu.flag_c}")
    print(f"   PC=0x{cpu.pc:02X}  MAR=0x{cpu.mar:02X}  IR=0x{cpu.ir:02X}")

    dump_ram(cpu)
    passed, failed = verify(cpu)

    print(f"\n{'='*60}")
    print(f" FINAL: {passed} passed, {failed} failed, "
          f"{passed + failed} total")
    print(f"{'='*60}")

    sys.exit(0 if failed == 0 else 1)


if __name__ == "__main__":
    main()
